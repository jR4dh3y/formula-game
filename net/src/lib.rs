/// Physics ticks between snapshots. Snapshots fall on multiples of this tick,
/// and both server and clients round race state to the wire precision there.
pub const SNAPSHOT_INTERVAL: u64 = racecraft_sim::PHYSICS_RATE as u64 / SNAPSHOT_RATE;

/// Round the race to exactly what a snapshot carries and continue from that.
///
/// The server does this on every snapshot tick; clients do the same on the
/// same ticks while predicting. Both then step from bit-identical state, so a
/// prediction with the right inputs matches the next snapshot exactly.
pub fn quantize(race: &mut Race) -> Result<codec::Encoded, String> {
    let encoded = codec::encode(&race.snapshot())?;
    race.restore(&codec::decode(&encoded)?)?;
    Ok(encoded)
}

fn default_ai_power() -> f64 {
    1.
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct RaceSettings {
    pub track: String,
    pub car: String,
    pub laps: u32,
    /// Exact number of server-controlled cars in addition to connected humans.
    /// The server keeps the combined field at `MAX_PLAYERS` or below.
    pub ai_cars: usize,
    #[serde(default = "default_ai_power")]
    pub ai_power: f64,
    pub lock_aids: bool,
    pub assists: Assists,
    pub corner_braking: f64,
    pub setup: Setup,
}
impl Default for RaceSettings {
    fn default() -> Self {
        Self {
            track: "spa".into(),
            car: "rb6".into(),
            laps: 3,
            ai_cars: 0,
            ai_power: default_ai_power(),
            lock_aids: true,
            assists: Assists {
                automatic_gears: true,
                ..Assists::default()
            },
            corner_braking: 1.,
            setup: Setup::default(),
        }
    }
}
impl RaceSettings {
    pub fn validate(&self) -> Result<(), String> {
        if !matches!(self.car.as_str(), "rb6" | "gen22")
            || self.track.is_empty()
            || self.track.len() > 32
            || !self
                .track
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'_')
            || !(1..=100).contains(&self.laps)
            || self.ai_cars >= MAX_PLAYERS
            || !self.ai_power.is_finite()
            || !(0.5..=1.).contains(&self.ai_power)
        {
            return Err("invalid car, circuit, lap count or AI car count".into());
        }
        if [
            self.assists.steering,
            self.assists.braking,
            self.assists.traction,
            self.assists.stability,
            self.corner_braking,
        ]
        .iter()
        .any(|x| !x.is_finite() || !(0. ..=1.).contains(x))
            || [self.setup.front_wing, self.setup.rear_wing]
                .iter()
                .any(|x| !x.is_finite() || !(0. ..=10.).contains(x))
        {
            return Err("invalid aids or wing settings".into());
        }
        Ok(())
    }
}
/// Bump when the protocol changes in a way the build hash cannot see.
pub const PROTOCOL_VERSION: u32 = 2;
/// Hash of every `sim` and `net` source file and of the locked versions of the
/// crates they compute with, generated by `build.rs`. Two builds join each
/// other only when their physics, prediction and wire code are identical.
pub const BUILD_HASH: &str = env!("RACECRAFT_BUILD_HASH");

/// Simulation inputs from the asset directory. Visual meshes and textures are
/// presentation only and stay local, like other graphics choices.
fn simulation_files(root: &Path, settings: &RaceSettings) -> Vec<std::path::PathBuf> {
    let track = root.join("tracks").join(&settings.track);
    let car = root.join("cars").join(&settings.car);
    let mut files = vec![
        track.join("track.json"),
        track.join("collision.bin"),
        car.join("car.json"),
    ];
    if settings.car == "gen22" {
        // The server assigns driver identities from this roster.
        files.push(car.join("teams.json"));
    }
    files
}

/// Fingerprint of this build and the selected circuit/car simulation assets.
pub fn fingerprint(root: &Path, settings: &RaceSettings) -> Result<[u8; 32], String> {
    settings.validate()?;
    let mut hash = Sha256::new();
    hash.update(b"racecraft-net");
    hash.update(PROTOCOL_VERSION.to_le_bytes());
    hash.update(BUILD_HASH.as_bytes());
    for file in simulation_files(root, settings) {
        let name = file
            .strip_prefix(root)
            .map_err(|e| e.to_string())?
            .to_string_lossy()
            .replace('\\', "/");
        hash.update((name.len() as u64).to_le_bytes());
        hash.update(name.as_bytes());
        let mut input =
            std::fs::File::open(&file).map_err(|e| format!("{}: {e}", file.display()))?;
        let len = input.metadata().map_err(|e| e.to_string())?.len();
        hash.update(len.to_le_bytes());
        std::io::copy(&mut input, &mut HashWriter(&mut hash)).map_err(|e| e.to_string())?;
    }
    Ok(hash.finalize().into())
}
struct HashWriter<'a>(&'a mut Sha256);
impl std::io::Write for HashWriter<'_> {
    fn write(&mut self, b: &[u8]) -> std::io::Result<usize> {
        self.0.update(b);
        Ok(b.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}
/// Asset-only initialization shared by the server and graphical client.
pub fn load_race(root: &Path, settings: &RaceSettings, players: &[Player]) -> Result<Race, String> {
    settings.validate()?;
    if players.is_empty() || players.len() > MAX_PLAYERS {
        return Err("race needs 1–16 players".into());
    }
    let track = Arc::new(Track::load(root.join("tracks").join(&settings.track))?);
    let geometry = CarGeometry::load(root.join("cars").join(&settings.car).join("car.json"))?;
    let spec = Arc::new(if settings.car == "rb6" {
        CarSpec::rb6_with(&geometry)
    } else {
        CarSpec::gen22_with(&geometry)
    });
    let count = players
        .len()
        .checked_add(settings.ai_cars)
        .filter(|&count| count <= MAX_PLAYERS)
        .ok_or("The selected AI count leaves no room for this many human drivers")?;
    let configs = (0..count)
        .map(|slot| {
            let player = players.get(slot);
            let mut assists = if settings.lock_aids {
                settings.assists
            } else {
                player.map_or(settings.assists, |p| p.assists)
            };
            assists.drs_anywhere = settings.assists.drs_anywhere;
            EntrantConfig {
                name: player.map_or_else(|| format!("AI {}", slot + 1), |p| p.name.clone()),
                spec: spec.clone(),
                setup: settings.setup,
                assists,
                ai: player
                    .is_none_or(|p| !p.connected)
                    .then_some(DriverProfile {
                        pace: 0.95,
                        aggression: 0.5,
                        consistency: 0.9,
                    }),
                human_slot: slot,
                livery: [1.; 3],
            }
        })
        .collect();
    let mut race = Race::new(track, configs, settings.laps, 0x5eed);
    race.set_ai_power(settings.ai_power);
    Ok(race)
}

/// GEN22 keeps stock team/driver identities unique; unspecified selections get a free driver.
pub fn select_identity(
    root: &Path,
    car: &str,
    requested: Option<DriverIdentity>,
    players: &[Player],
) -> Result<Option<DriverIdentity>, String> {
    if car != "gen22" {
        return Ok(None);
    }
    #[derive(Deserialize)]
    struct Roster {
        teams: Vec<Team>,
    }
    #[derive(Deserialize)]
    struct Team {
        id: String,
        drivers: Vec<NamedDriver>,
    }
    #[derive(Deserialize)]
    struct NamedDriver {
        id: String,
    }
    let roster: Roster = serde_json::from_slice(
        &std::fs::read(root.join("cars/gen22/teams.json")).map_err(|e| e.to_string())?,
    )
    .map_err(|e| e.to_string())?;
    let available: Vec<_> = roster
        .teams
        .into_iter()
        .flat_map(|team| {
            team.drivers.into_iter().map(move |driver| DriverIdentity {
                team: team.id.clone(),
                driver: driver.id,
            })
        })
        .collect();
    let used = |identity: &DriverIdentity| {
        players
            .iter()
            .any(|p| p.identity.as_ref() == Some(identity))
    };
    match requested {
        Some(identity) if !available.contains(&identity) => {
            Err("Unknown team/driver identity".into())
        }
        Some(identity) if used(&identity) => Err(
            "That team/driver is already selected. Choose another or use automatic assignment."
                .into(),
        ),
        Some(identity) => Ok(Some(identity)),
        None => available
            .into_iter()
            .find(|i| !used(i))
            .map(Some)
            .ok_or_else(|| "No free drivers remain".into()),
    }
}
